const DICTS: Record<Lang, Dict> = { en, zh, ms }

/** 称谓列表(马来西亚常用),不翻译 */
export const TITLES = [
  'Mr', 'Mrs', 'Ms', 'Miss', 'Mdm', 'Dr', 'Prof', 'Encik', 'Puan', 'Cik',
  "Dato'", 'Datin', 'Datuk', 'Tan Sri', 'Puan Sri', 'Tun', 'Haji', 'Hajah',
]

export type T = (key: Key, vars?: Record<string, string | number>) => string

function readLang(): Lang {
  try {
    const v = localStorage.getItem('lang')
    if (v === 'en' || v === 'zh' || v === 'ms') return v
  } catch { /* 隐私模式等情况下 localStorage 不可用 */ }
  return 'en'
}

interface I18n { lang: Lang; setLang: (l: Lang) => void; t: T }
const Ctx = createContext<I18n | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)
  useEffect(() => { document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang }, [lang])
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('lang', l) } catch { /* ignore */ }
  }, [])
  const t = useCallback<T>((key, vars) => {
    let s = DICTS[lang][key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }, [lang])
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n outside LangProvider')
  return v
}

export function LangSwitcher() {
  const { lang, setLang, t } = useI18n()
  return (
    <select className="langsel" aria-label={t('common.language')} value={lang} onChange={(e) => setLang(e.target.value as Lang)}>
      {LANGS.map((l) => <option key={l.code} value={l.code}>{l.code === 'en' ? 'EN' : l.code === 'zh' ? '中文' : 'BM'}</option>)}
    </select>
  )
}

/** 信件 error 字段("CODE" 或 "CODE:detail")→ 当前语言的提示 */
export function letterErrorText(t: T, error: string | null): string {
  if (!error) return ''
  const code = error.split(':')[0]
  const key = `lerr.${code}` as Key
  return key in en ? t(key) : error
}
